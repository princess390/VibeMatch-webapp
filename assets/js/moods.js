export function normalizeText(value) {
  return String(value || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^\p{L}\p{N}\s-]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

export function findMood(input) {
  const normalizedInput = normalizeText(input);

  if (!normalizedInput) return null;

  const stopWords = new Set([
    "akarok",
    "akarom",
    "szeretnek",
    "szeretnem",
    "valami",
    "valamilyen",
    "nagyon",
    "kicsit",
    "nekem",
    "most",
    "ma",
    "egy",
    "olyan",
    "ami",
    "amiben",
    "amivel",
    "utan",
    "elott"
  ]);

  const inputTokens = new Set(
    normalizedInput
      .split(/\s+/)
      .filter(token => token.length > 2 && !stopWords.has(token))
  );

  let bestMatch = null;
  let bestScore = 0;

  Object.entries(moodCategories).forEach(([key, mood]) => {
    const searchableTerms = [
      key,
      mood.label,
      ...(mood.keywords || []),
      ...(mood.apiKeywords || [])
    ];

    let score = 0;

    searchableTerms.forEach(term => {
      const normalizedTerm = normalizeText(term);
      if (!normalizedTerm) return;

      if (normalizedInput === normalizedTerm) {
        score += 120;
        return;
      }

      if (normalizedInput.includes(normalizedTerm)) {
        score += normalizedTerm.includes(" ") ? 80 : 45;
      }

      if (normalizedTerm.includes(normalizedInput) && normalizedInput.length >= 4) {
        score += 35;
      }

      normalizedTerm.split(/\s+/).forEach(termToken => {
        if (termToken.length <= 2) return;

        if (inputTokens.has(termToken)) {
          score += 18;
        }

        inputTokens.forEach(inputToken => {
          if (
            inputToken.length >= 5 &&
            termToken.length >= 5 &&
            (inputToken.startsWith(termToken) || termToken.startsWith(inputToken))
          ) {
            score += 8;
          }
        });
      });
    });

    if (score > bestScore) {
      bestScore = score;
      bestMatch = [key, mood];
    }
  });

  return bestScore >= 18 ? bestMatch : null;
}

export function getMoodByKey(key) {
  return moodCategories[key] || null;
}

export function getMoodLabels() {
  return Object.entries(moodCategories).map(([key, mood]) => ({
    key,
    label: mood.label
  }));
}
